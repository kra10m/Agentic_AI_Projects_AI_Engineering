from langchain_core.prompts import ChatPromptTemplate
# Assuming schema.py is in the same directory
from schema import CriticFeedback

# ---------------------------------------------------------
# 1. THE CRITIC PROMPT
# ---------------------------------------------------------
CRITIC_PROMPT = """You are the Lead Risk Critic for a Corporate Due Diligence team.
Your job is to evaluate the reports generated by the Qualitative Researcher and the Quantitative Analyst.

USER QUERY: {query}

--- QUALITATIVE REPORT (Researcher) ---
{qual_data}

--- QUANTITATIVE REPORT (Analyst) ---
{quant_data}

EVALUATION CRITERIA:
1. Are there glaring contradictions between the narrative (qualitative) and the numbers (quantitative)?
2. Is either report missing critical information needed to answer the User Query?
3. Are the responses realistic and logically sound?

INSTRUCTIONS:
- If both reports are solid and aligned, set is_approved to True, leave target_agent blank, and give a brief approval message.
- If you find an issue, set is_approved to False.
- You MUST select ONLY ONE target_agent ("Researcher" or "Analyst") to fix the most glaring issue first.
- Provide specific feedback_text detailing exactly what that agent needs to change or add.
- Do not demand absolute perfection. If the reports are generally aligned, make sense, and have no glaring logical contradictions, set is_approved to True.
"""

# ---------------------------------------------------------
# 2. THE CRITIC NODE
# ---------------------------------------------------------
def critic_node(state: dict, llm):
    print("\n[Critic] Evaluating specialist reports...")
    
    # 1. Extract the data to review
    qual_data = state.get("qualitative_data")
    quant_data = state.get("quantitative_data")
    
    # We format them into strings for the LLM prompt. If missing, flag it.
    qual_str = qual_data.model_dump_json(indent=2) if qual_data else "MISSING"
    quant_str = quant_data.model_dump_json(indent=2) if quant_data else "MISSING"
    
    # 2. Set up the LLM with structured output
    prompt = ChatPromptTemplate.from_template(CRITIC_PROMPT)
    structured_llm = llm.with_structured_output(CriticFeedback)
    chain = prompt | structured_llm
    
    # 3. Invoke the chain
    decision: CriticFeedback = chain.invoke({
        "query": state.get("query"),
        "qual_data": qual_str,
        "quant_data": quant_str
    })
    
    status = "APPROVED" if decision.is_approved else f"REJECTED -> Needs fix by {decision.target_agent}"
    print(f"[Critic] Decision: {status}")
    print(f"[Critic] Feedback: {decision.feedback_text}")
    
    # 4. Update the state
    # CRITICAL: Because 'critic_history' in our schema is annotated with operator.add,
    # returning a list here APPENDS this decision to the graph's history log.
    return {"critic_history": [decision], "revision_pending": False}